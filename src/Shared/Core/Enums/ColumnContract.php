<?php

declare(strict_types=1);

namespace App\Shared\Core\Enums;

/**
 * Column Contract.
 *
 * Defines the canonical contract between domain concepts and persistence
 * columns: conventional default values and standardized column comments,
 * so migrations stay consistent and self-documenting.
 *
 * @example
 * // In migration
 * 'status'      => $cb::smallint()->notNull()->defaultValue(ColumnContract::statusDefault())->comment(ColumnContract::statusComment()),
 * 'detail_info' => $cb::json()->notNull()->defaultValue(ColumnContract::DETAIL_INFO_DEFAULT)->comment(ColumnContract::DETAIL_INFO_COMMENT),
 * @example
 * // When a column deliberately deviates from the convention, pick the status
 * 'status' => $cb::smallint()->notNull()->defaultValue(ColumnContract::statusDefault('active'))->comment(ColumnContract::statusComment()),
 */
final class ColumnContract
{
    // -------------------------------------------------------------------------
    // Conventional Defaults
    // -------------------------------------------------------------------------

    /**
     * PostgreSQL identity clause for conventional `id` primary key columns.
     */
    public const PG_PRIMARY_KEY_IDENTITY = 'PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY';

    /**
     * MySQL auto-timestamp clause for `updated_at` columns — sets
     * CURRENT_TIMESTAMP on insert and refreshes it on every update.
     */
    public const MYSQL_TIMESTAMP_AUTO_UPDATE = 'DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP';

    /**
     * MySQL table-level options clause — charset, collation, and engine
     * for CREATE TABLE statements.
     */
    public const MYSQL_INNODB_COLLATION = 'CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci ENGINE=InnoDB';

    /**
     * Default value for `status` columns.
     *
     * Defaults to the conventional draft-first workflow; pass another
     * status name (case-insensitive) when a column deliberately starts
     * elsewhere.
     *
     * @param string $status RecordStatus case name, e.g. 'draft', 'active'
     *
     * @example
     * ->defaultValue(ColumnContract::statusDefault())          // Draft
     * ->defaultValue(ColumnContract::statusDefault('active'))  // Active
     */
    public static function statusDefault(string $status = 'draft'): int
    {
        $constant = RecordStatus::class . '::' . \strtoupper($status);

        if (!\defined($constant)) {
            throw new \InvalidArgumentException("Unknown status '{$status}'");
        }

        return \constant($constant)->value;
    }

    /**
     * Canonical initial payload for `detail_info` JSON columns.
     *
     * Mirrors the empty change_log shape owned by the ChangeLogged concern;
     * DetailInfoFactory populates real values on every write.
     */
    public const DETAIL_INFO_DEFAULT = [
        'change_log' => [
            'created_at' => null,
            'created_by' => null,
            'updated_at' => null,
            'updated_by' => null,
            'deleted_at' => null,
            'deleted_by' => null,
        ],
    ];

    /**
     * Conventional default for `sync_flag` columns (1 = not synced).
     */
    public const SYNC_FLAG_DEFAULT = 1;

    /**
     * Conventional default for `lock_version` columns (optimistic locking).
     */
    public const LOCK_VERSION_DEFAULT = 1;

    // -------------------------------------------------------------------------
    // Standardized Comments
    // -------------------------------------------------------------------------

    /**
     * Standard comment for `detail_info` columns.
     */
    public const DETAIL_INFO_COMMENT = 'JSON detail info — change_log{created_at, created_by, updated_at, updated_by, deleted_at, deleted_by} + module-specific keys';

    /**
     * Standard comment for `origin_id` columns.
     */
    public const ORIGIN_ID_COMMENT = 'origin instance id where the record comes from or goes to';

    /**
     * Standard comment for `sync_flag` columns.
     */
    public const SYNC_FLAG_COMMENT = 'null: synced, 1: not synced';

    /**
     * Standard comment for `sync_mdb` columns.
     */
    public const SYNC_MDB_COMMENT = 'null: sync to MDB, 1: not sync to MDB';

    /**
     * Standard comment for `lock_version` columns.
     */
    public const LOCK_VERSION_COMMENT = 'Optimistic locking version';

    /**
     * Standard comment for `status` columns.
     *
     * Kept as a method — the legend is generated from RecordStatus and
     * cannot be a const expression.
     *
     * @return string Status legend, e.g. "0: Inactive, 1: Active, ..."
     */
    public static function statusComment(): string
    {
        return RecordStatus::describe();
    }
}
